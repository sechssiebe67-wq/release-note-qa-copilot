"""Render a Markdown release-note draft with inline QA annotations."""

from __future__ import annotations

from typing import Dict, List, Optional

from .grouping import group_entries, group_titles
from .models import (
    ChangeEntry,
    Flag,
    QAResult,
)
from .qa import checklist
from .templates import ReleaseTemplate, default_template


_SEVERITY_ICON = {
    "high": "\u2757",  # ❗
    "medium": "\u26a0",  # ⚠
    "low": "\u2139",  # ℹ
}


def _status_icon(status: str) -> str:
    if status == "pass":
        return "\u2705"  # ✅
    if status == "warn":
        return "\u26a0"  # ⚠
    return "\u274c"  # ❌


def _source_line(entry: ChangeEntry) -> str:
    if entry.source and entry.link:
        return "**Source:** [{}]({})".format(entry.source, entry.link)
    if entry.link:
        return "**Source:** <{}>".format(entry.link)
    if entry.source:
        return "**Source:** {}".format(entry.source)
    return "**Source:** _(none provided)_"


def render_entry(entry: ChangeEntry, flags: List[Flag]) -> List[str]:
    """Render a single entry as Markdown lines."""
    lines: List[str] = []
    title = entry.title.strip() or "(untitled change)"
    lines.append("### {}".format(title))
    if entry.description.strip():
        lines.append(entry.description.strip())
    details: List[str] = []
    if entry.benefit.strip():
        details.append("**Customer benefit:** {}".format(entry.benefit.strip()))
    if entry.audience.strip():
        details.append("**Audience:** {}".format(entry.audience.strip()))
    details.append(_source_line(entry))
    if entry.id:
        details.append("**ID:** `{}`".format(entry.id))
    for detail in details:
        lines.append("- {}".format(detail))
    for flag in flags:
        icon = _SEVERITY_ICON.get(flag.severity, "\u2139")
        lines.append(
            "- {} **QA `{}`:** {}".format(icon, flag.code, flag.message)
        )
    return lines


def render_qa_checklist(items: List[Dict[str, str]]) -> List[str]:
    """Render the QA checklist as Markdown lines."""
    lines = ["## QA Checklist", ""]
    for item in items:
        lines.append(
            "- {} {} — {}".format(
                _status_icon(item["status"]),
                item["label"],
                item["detail"],
            )
        )
    return lines


def render_markdown(
    title: str,
    entries: List[ChangeEntry],
    qa: QAResult,
    template: Optional[ReleaseTemplate] = None,
) -> str:
    """Render the complete Markdown release-note draft.

    ``template`` controls the section order and the optional intro/outro.
    Empty sections are skipped unless the template marks them ``required``, in
    which case an explicit ``_(no entries)_`` placeholder is rendered. When no
    template is given the built-in ``default`` layout is used, which reproduces
    the historical output exactly.
    """
    template = template or default_template()
    groups = group_entries(entries)
    titles = group_titles()
    flags_by_entry: Dict[str, List[Flag]] = {}
    for flag in qa.flags:
        flags_by_entry.setdefault(flag.entry_id, []).append(flag)

    lines: List[str] = []
    header = title.strip() or "Release Notes"
    lines.append("# {}".format(header))
    lines.append("")
    flagged = len({f.entry_id for f in qa.flags})
    lines.append(
        "_Generated by Release Note QA Copilot · {} entr{} · {} flagged · "
        "{} high severity_".format(
            len(entries),
            "y" if len(entries) == 1 else "ies",
            flagged,
            len(qa.high),
        )
    )
    lines.append("")

    if template.intro.strip():
        lines.append(template.intro.strip())
        lines.append("")

    for section in template.sections:
        group_entries_list = groups.get(section.key, [])
        if not group_entries_list:
            if not section.required:
                continue
            lines.append(
                "## {}".format(titles.get(section.key, section.key.title()))
            )
            lines.append("")
            lines.append("_(no entries)_")
            lines.append("")
            continue
        lines.append("## {}".format(titles.get(section.key, section.key.title())))
        lines.append("")
        for entry in group_entries_list:
            lines.extend(render_entry(entry, flags_by_entry.get(entry.id, [])))
            lines.append("")

    if template.outro.strip():
        lines.append(template.outro.strip())
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.extend(render_qa_checklist(checklist(entries, qa)))
    lines.append("")
    lines.append(
        "_Review before publishing: confirm every source and remove the QA "
        "annotations once resolved._"
    )
    lines.append("")
    return "\n".join(lines)
